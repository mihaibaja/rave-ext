static uint32_t rave_vinstr_hash(const char *s){
    uint32_t h = 2166136261u;   /* FNV-1a */
    for (; *s; ++s) { h ^= (unsigned char)*s; h *= 16777619u; }
    return h;
}

int rave_vinstr_lookup(const char *mnemonic){
    uint32_t slot;
    int probe;
    if (mnemonic == NULL || mnemonic[0] != 'v') return -1;
    slot = rave_vinstr_hash(mnemonic) & (RAVE_VINSTR_HASH_SIZE - 1);
    for (probe = 0; probe < RAVE_VINSTR_HASH_SIZE; ++probe) {
        short idx = rave_vinstr_slots[(slot + probe) & (RAVE_VINSTR_HASH_SIZE - 1)];
        if (idx < 0) return -1;
        if (strcmp(rave_vinstr_mnemonics[idx], mnemonic) == 0) return idx;
    }
    return -1;
}

